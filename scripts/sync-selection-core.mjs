import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname,join} from 'node:path';
import {createHash} from 'node:crypto';

// Exported for an isolated regression test. No network, credentials or model calls.
export function generateSelectionCore(root,check=false,mobileCheckout) {
  const read=path=>readFileSync(join(root,path),'utf8').replace(/\r\n/g,'\n');
  const policy=JSON.parse(read('selection-core/policy.json'));
  if(policy.schemaVersion!==1||typeof policy.version!=='string'||!Number.isInteger(policy.defaults.artistShareDivisor)||policy.defaults.artistShareDivisor<2)throw Error('Invalid selection policy.');
  const shares={2:'one half',3:'one third',4:'one quarter',5:'one fifth',10:'one tenth'};
  const minimums={1:'one',2:'two',3:'three'};
  const prompt=name=>read('selection-core/prompts/'+name+'.txt').trim().split('\n').map(line=>line.trim()).filter(Boolean).join(' ')
    .replaceAll('{{artistShare}}',shares[policy.defaults.artistShareDivisor]??`1/${policy.defaults.artistShareDivisor}`)
    .replaceAll('{{minimumOtherArtistSongs}}',minimums[policy.defaults.minimumOtherArtistSongs]??String(policy.defaults.minimumOtherArtistSongs));
  const common=prompt('curation'), helper=prompt('helper'), mobile=prompt('mobile'), briefPrompt=prompt('brief');
  const briefSchema=JSON.parse(read('selection-core/brief.schema.json'));
  const songSchema={type:'object',additionalProperties:false,properties:{title:{type:'string'},artist:{type:'string'}},required:['title','artist']};
  const helperSchema={type:'object',additionalProperties:false,properties:{brief:briefSchema,ids:{type:'array',items:{type:'string'}},suggestions:{type:'array',items:songSchema}},required:['brief','ids','suggestions']};
  const mobileSchema={type:'object',additionalProperties:false,properties:{brief:briefSchema,songs:{type:'array',items:songSchema}},required:['brief','songs']};
  const source=read('selection-core/curation.ts');
  const fingerprint=createHash('sha256').update(JSON.stringify({policy,common,helper,mobile,briefPrompt,briefSchema,source})).digest('hex');
  const header=`// Generated by scripts/sync-selection-core.mjs. Edit selection-core/, then regenerate.\n// Policy ${policy.version}; source SHA-256 ${fingerprint}\n`;
  const ts=header+source.replace("import selectionPolicy from './policy.json';",`export const selectionPolicy = ${JSON.stringify(policy,null,2)} as const;\nexport const selectionPolicyHash = ${JSON.stringify(fingerprint)};\nexport const curationInstructions = ${JSON.stringify(common)};\nexport const briefInstructions = ${JSON.stringify(briefPrompt)};\nexport const mobileInstructions = ${JSON.stringify(mobile+' '+common+' '+briefPrompt)};\nexport const mobileResponseSchema = ${JSON.stringify(mobileSchema)};`);
  if(ts===header+source)throw Error('Selection core policy import was not found.');
  const literal=value=>JSON.stringify(value);
  const list=values=>'['+values.map(literal).join(', ')+']';
  const cs=header+`namespace QueueCompanion;
public static class SelectionPolicy
{
    public const string Version = ${literal(policy.version)};
    public const string SourceHash = ${literal(fingerprint)};
    public const string CurationInstructions = ${literal(common)};
    public const string HelperInstructions = ${literal(helper+' '+common)};
    public const string BriefInstructions = ${literal(briefPrompt)};
    public const string BriefSchemaJson = ${literal(JSON.stringify(briefSchema))};
    public const string ResponseSchemaJson = ${literal(JSON.stringify(helperSchema))};
    public const string ChatGptFamily = ${literal(policy.models.chatgpt.preferredFamily)};
    public const string ClaudeFamily = ${literal(policy.models.claude.preferredFamily)};
    public static readonly string[] ClaudeFallbackFamilies = ${list(policy.models.claude.fallbackFamilies)};
    public static readonly string[] ChatGptLowEffortFamilies = ${list(policy.models.chatgpt.lowEffortFamilies)};
    public static readonly string[] ClaudeLowEffortModels = ${list(policy.models.claude.lowEffortModels)};
    public const string Effort = ${literal(policy.models.effort)};
}
public record MusicBrief(${Object.entries(briefSchema.properties).filter(([key])=>!['referenceType','collectiveMembers'].includes(key)).map(([key,value])=>(value.type==='array'?'string[]':value.type==='integer'?'int':'string')+' '+key[0].toUpperCase()+key.slice(1)).join(', ')}, string? ReferenceType = null, string[]? CollectiveMembers = null);
`;
  const lock=JSON.stringify({schemaVersion:1,version:policy.version,sourceHash:fingerprint,generatedHash:createHash('sha256').update(ts).digest('hex')},null,2)+'\n';
  const outputs=new Map([['extension/src/curation.ts',ts],['mobile/lib/queue/curation.ts',ts],['mobile/selection-core.lock.json',lock],['helper/SelectionPolicy.g.cs',cs]]);
  if(mobileCheckout){outputs.set(join(resolve(mobileCheckout),'lib/queue/curation.ts'),ts);outputs.set(join(resolve(mobileCheckout),'selection-core.lock.json'),lock);}
  const stale=[];
  for(const [path,value]of outputs) {
    const target=resolve(root,path);
    let existing;try{existing=readFileSync(target,'utf8').replace(/\r\n/g,'\n');}catch{}
    if(existing===value)continue;
    if(check){stale.push(path);continue;}
    mkdirSync(dirname(target),{recursive:true});writeFileSync(target,value);
  }
  if(stale.length)throw Error('Shared selection outputs are stale: '+stale.join(', ')+'. Run node scripts/sync-selection-core.mjs, then rebuild both apps.');
  return {version:policy.version,fingerprint,outputs:[...outputs.keys()]};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  try {const result=generateSelectionCore(fileURLToPath(new URL('..',import.meta.url)),process.argv.includes('--check'),process.argv.find(arg=>arg.startsWith('--mobile-checkout='))?.slice('--mobile-checkout='.length));console.log(`Selection core ${result.version}: ${process.argv.includes('--check')?'verified':'synchronized'} (${result.fingerprint.slice(0,12)})`);}
  catch(error){console.error(error.message);process.exitCode=1;}
}
